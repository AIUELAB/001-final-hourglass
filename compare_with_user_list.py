    # カテゴリ別に出力
    for category, persons in categories.items():
        if persons:
            print(f"\n【{category}】({len(persons)}人)")
            for person in persons[:20]:  # 最初の20人まで表示
                print(f"  - {person}")
            if len(persons) > 20:
                print(f"  ... 他{len(persons)-20}人")

