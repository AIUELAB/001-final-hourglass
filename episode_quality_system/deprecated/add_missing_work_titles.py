    def analyze_current_episodes(self, csv_path: str):
        """現在のエピソードを分析して作品名の有無をチェック"""

        df = pd.read_csv(csv_path, encoding='utf-8-sig')

        print("作品名・大会名チェック結果")
        print("="*60)

        missing_proper_nouns = []

        for _, row in df.iterrows():
            episode = row['episode']
            person_name = row['person_name']

            # 固有名詞（「」内）をチェック
            quoted_items = re.findall(r'「[^」]+」', episode)

            # 大会名・企業名のパターンをチェック
            has_tournament = bool(re.search(r'(五輪|オリンピック|ワールドカップ|WBC|世界選手権|全米オープン|マスターズ|グランプリ|アジア選手権|選手権)', episode))
            has_company = bool(re.search(r'(株式会社|Inc\.|Corporation|Ltd\.|楽天|ソフトバンク|トヨタ|ソニー|パナソニック)', episode))

            # 問題があるエピソードを記録
            if not quoted_items and not has_tournament and not has_company:
                # エンターテインメント・文化系の人物
                if any(word in episode for word in ['歴史的な偉業', '重要な成果', '専門分野で']):
                    missing_proper_nouns.append({
                        'name': person_name,
                        'issue': 'テンプレート文章・作品名なし',
                        'episode_preview': episode[:50] + '...'
                    })
                elif person_name in ['星野源', '新海誠', '綾瀬はるか', '西野亮廣', '村上春樹', '福山雅治']:
                    missing_proper_nouns.append({
                        'name': person_name,
                        'issue': '作品名が不足',
                        'episode_preview': episode[:50] + '...'
                    })

        if missing_proper_nouns:
            print(f"\n作品名・大会名が不足: {len(missing_proper_nouns)}件")
            for item in missing_proper_nouns[:10]:
                print(f"  - {item['name']}: {item['issue']}")

        return missing_proper_nouns

