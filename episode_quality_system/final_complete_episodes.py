    def get_episode(self, person_name: str, age: int) -> str:
        """エピソードを取得"""
        if person_name in self.complete_episodes:
            return self.complete_episodes[person_name]
        else:
            # デフォルトテンプレート使用
            return self.complete_episodes['DEFAULT'].format(age=age, name=person_name)

    def update_database(self, input_csv: str):
        """データベースを更新"""

        # 既存データ読み込み
        df = pd.read_csv(input_csv, encoding='utf-8-sig')

        print(f"データベース更新開始: {len(df)}件")

        updated_count = 0
        for idx, row in df.iterrows():
            person_name = row['person_name']
            age = row['age']

            # 新しいエピソード取得
            new_episode = self.get_episode(person_name, age)

            # デフォルトテンプレートでない場合は更新
            if person_name in self.complete_episodes and person_name != 'DEFAULT':
                df.at[idx, 'episode'] = new_episode
                df.at[idx, 'character_count'] = len(new_episode)
                df.at[idx, 'quality_score'] = 10.0  # 最高品質
                df.at[idx, 'source'] = 'final_complete'
                updated_count += 1

        # 保存
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        output_csv = f"final_complete_episodes_{timestamp}.csv"
        df.to_csv(output_csv, index=False, encoding='utf-8-sig')

        print(f"\n更新完了:")
        print(f"  - 更新エピソード数: {updated_count}")
        print(f"  - 出力ファイル: {output_csv}")

        # 品質チェック
        valid = df[(df['character_count'] >= 132) & (df['character_count'] <= 250)]
        print(f"\n品質指標:")
        print(f"  ✅ 文字数適正率: {len(valid)/len(df)*100:.1f}%")
        print(f"  • 平均文字数: {df['character_count'].mean():.1f}")

        return output_csv


