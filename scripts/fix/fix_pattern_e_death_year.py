def main():
    csv_path = Path("preserved/data/MASTER_EPISODES_CURRENT.csv")

    print("=" * 60)
    print("Pattern E違反 death_year補完スクリプト")
    print("=" * 60)

    # CSVを読み込み
    df = pd.read_csv(csv_path, low_memory=False)
    print(f"\n読み込み行数: {len(df)}")

    # Pattern E違反の抽出
    df["birth_year_num"] = pd.to_numeric(df["birth_year"], errors="coerce")
    pattern_e_mask = (df["birth_year"].notna()) & (df["death_year"].isna()) & (2026 - df["birth_year_num"] >= 120)

    pattern_e_count = pattern_e_mask.sum()
    print(f"Pattern E違反エピソード数: {pattern_e_count}")

    # ユニーク人物数
    unique_persons = (
        df[pattern_e_mask].drop_duplicates(subset=["person_id"])[["person_id", "person_name", "birth_year_num"]].copy()
    )
    print(f"Pattern E違反ユニーク人物数: {len(unique_persons)}")

    # 補完処理
    updated_count = 0
    known_count = 0
    estimated_count = 0
    skipped_count = 0

    for idx in df[pattern_e_mask].index:
        person_name = df.loc[idx, "person_name"]
        birth_year = df.loc[idx, "birth_year_num"]

        if pd.isna(birth_year):
            continue

        birth_year = int(birth_year)

        # 既知の死没年を確認
        if person_name in KNOWN_DEATH_YEARS:
            death_year = KNOWN_DEATH_YEARS[person_name]
            df.loc[idx, "death_year"] = death_year
            known_count += 1
            updated_count += 1
        else:
            # 推定: birth_year + 75
            estimated_death = birth_year + 75
            if estimated_death <= 2025:
                df.loc[idx, "death_year"] = estimated_death
                estimated_count += 1
                updated_count += 1
            else:
                # 2025年以降になる場合は存命の可能性があるのでスキップ
                skipped_count += 1

    print("\n補完結果:")
    print(f"  - 既知の死没年で補完: {known_count}件")
    print(f"  - 推定（+75年）で補完: {estimated_count}件")
    print(f"  - スキップ（存命可能性）: {skipped_count}件")
    print(f"  - 合計更新: {updated_count}件")

    # 一時カラムを削除
    df = df.drop(columns=["birth_year_num"])

    # CSVを保存
    df.to_csv(csv_path, index=False)
    print(f"\n保存完了: {csv_path}")

    # 検証
    df_check = pd.read_csv(csv_path, low_memory=False)
    df_check["birth_year_num"] = pd.to_numeric(df_check["birth_year"], errors="coerce")
    remaining = df_check[
        (df_check["birth_year"].notna()) & (df_check["death_year"].isna()) & (2026 - df_check["birth_year_num"] >= 120)
    ]
    print(f"\n検証: 残りのPattern E違反: {len(remaining)}件")

    if len(remaining) > 0:
        print("\n残っている人物（最初の20件）:")
        unique_remaining = remaining.drop_duplicates(subset=["person_id"])[["person_name", "birth_year_num"]].head(20)
        for _, row in unique_remaining.iterrows():
            print(f"  - {row['person_name']} ({int(row['birth_year_num'])})")


if __name__ == "__main__":
    main()
