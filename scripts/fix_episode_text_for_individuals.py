def main():
    csv_path = "preserved/data/MASTER_EPISODES_CURRENT.csv"
    df = pd.read_csv(csv_path, low_memory=False)

    fixed = 0
    for ep_id, fix in TEXT_FIXES.items():
        mask = df["episode_id"] == ep_id
        if mask.any():
            current = df.loc[mask, "episode_text"].values[0]
            if current == fix["old"]:
                df.loc[mask, "episode_text"] = fix["new"]
                fixed += 1
                print(f"  修正: {ep_id}")
            else:
                print(f"  スキップ: {ep_id}（テキスト不一致）")

    df.to_csv(csv_path, index=False)
    print(f"\n完了: {fixed}件のテキスト修正")


if __name__ == "__main__":
    main()
