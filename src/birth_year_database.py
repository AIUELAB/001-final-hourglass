def get_birth_year(person_name: str) -> Optional[int]:
    """
    人物名から生年を取得

    Args:
        person_name: 人物名

    Returns:
        生年（見つからない場合はNone）
    """
    # 完全一致
    if person_name in BIRTH_YEARS:
        return BIRTH_YEARS[person_name]

    # 部分一致（例：「松本人志」が「ダウンタウン松本人志」にマッチ）
    for name, year in BIRTH_YEARS.items():
        if person_name in name or name in person_name:
            return year

    return None


def calculate_episode_year(person_name: str, age: int) -> Optional[int]:
    """
    人物名と年齢からエピソードの年を計算

    Args:
        person_name: 人物名
        age: エピソードの年齢

    Returns:
        エピソードの年（生年が不明な場合はNone）
    """
    birth_year = get_birth_year(person_name)
    if birth_year is None:
        return None
    return birth_year + age


def is_future_episode(person_name: str, age: int, current_year: Optional[int] = None) -> bool:
    """
    未来のエピソードかどうかを判定

    Args:
        person_name: 人物名
        age: エピソードの年齢
        current_year: 現在の年（デフォルトは実際の現在年）

    Returns:
        未来のエピソードならTrue
    """
    if current_year is None:
        current_year = CURRENT_YEAR

    episode_year = calculate_episode_year(person_name, age)
    if episode_year is None:
        # フェイルセーフ: 生年不明かつ高齢は未来エピソードとして扱う
        # EP-000018問題の再発防止
        if age >= 60:
            return True  # 高齢で生年不明は未来扱い（ブロック推奨）
        return False  # それ以外は判定不能

    return episode_year > current_year


def get_max_valid_age(person_name: str, current_year: Optional[int] = None) -> Optional[int]:
    """
    現在までに達成可能な最大年齢を取得

    Args:
        person_name: 人物名
        current_year: 現在の年

    Returns:
        最大有効年齢（生年不明の場合はNone）
    """
    if current_year is None:
        current_year = CURRENT_YEAR

    birth_year = get_birth_year(person_name)
    if birth_year is None:
        return None

    return current_year - birth_year


def validate_episode_age(
    person_name: str,
    age: int,
    person_type: str = "REAL",
    current_year: Optional[int] = None,
) -> tuple[bool, str]:
    """
    エピソードの年齢が妥当かどうかを検証

    Args:
        person_name: 人物名
        age: エピソードの年齢
        person_type: 人物タイプ（REAL/FICTIONAL）
        current_year: 現在の年

    Returns:
        (有効かどうか, エラーメッセージ or "OK")
    """
    if current_year is None:
        current_year = CURRENT_YEAR

    # 架空キャラクターは年齢制限なし
    if person_type != "REAL":
        return True, "OK"

    # 年齢の基本チェック
    if age < 0:
        return False, f"年齢が負の値です: {age}"

    if age > 130:
        return False, f"年齢が130歳を超えています: {age}"

    # 生年データベースでチェック
    birth_year = get_birth_year(person_name)
    if birth_year is None:
        # フェイルセーフ設計: 高齢・幼少エピソードは生年不明時にブロック
        # EP-000018問題（桜井日奈子66歳）の再発防止
        if age >= 60:
            return False, f"BLOCK: 高齢エピソード（{age}歳）で生年データなし - 要手動登録"
        elif age <= 10:
            return False, f"BLOCK: 幼少期エピソード（{age}歳）で生年データなし - 要手動登録"
        else:
            # 中間年齢は警告付きで許可（ただしフラグ付き）
            return True, f"WARN: 生年データなし（{person_name}）- 手動確認推奨"

    episode_year = birth_year + age
    max_age = current_year - birth_year

    if episode_year > current_year:
        return False, f"未来のエピソード: {person_name}の{age}歳は{episode_year}年（現在{current_year}年）"

    if age > max_age:
        return False, f"年齢超過: {person_name}は現在{max_age}歳まで（{age}歳は不可）"

    return True, "OK"


