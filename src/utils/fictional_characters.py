def is_fictional_character(name: str) -> bool:
    """
    名前が架空キャラクターかどうかを判定

    Args:
        name: 人物名

    Returns:
        True if the name is a known fictional character
    """
    if not name:
        return False

    # ブラックリストにある名前は除外（誤検出防止）
    if name in BLACKLIST_NAMES:
        return False

    # 完全一致チェック
    return name in ALL_FICTIONAL_CHARACTERS


def get_work_for_character(name: str) -> str | None:
    """
    キャラクター名から作品タイトルを取得

    Args:
        name: キャラクター名

    Returns:
        作品タイトル（見つからない場合はNone）
    """
    if not name or name in BLACKLIST_NAMES:
        return None

    for work_title, characters in FICTIONAL_CHARACTERS.items():
        if name in characters:
            return work_title

    return None


def normalize_fictional_name(name: str) -> tuple[str, bool]:
    """
    架空キャラクター名を正規形式に変換

    Args:
        name: 人物名

    Returns:
        (正規化された名前, 変換が行われたかどうか)
    """
    if not name:
        return name, False

    if name in FICTIONAL_NAME_ALIASES:
        return FICTIONAL_NAME_ALIASES[name], True

    return name, False
